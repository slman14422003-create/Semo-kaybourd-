#!/usr/bin/env python3
"""
يولّد تصحيحات عربية (خطأ ← صواب) من قائمة تردّدات كلمات ويكتب الناتج في assets/dict/ar_fix_auto.txt.
يُستدعى من .github/workflows/update-ar-fix.yml، ويمكن تشغيله يدويًا:

  python3 tools/build_ar_fix.py --freq ar_freq.txt --out app/src/main/assets/dict/ar_fix_auto.txt

صيغة --freq: سطر لكل كلمة «كلمة[مسافة أو Tab]العدد»، أو كلمة فقط (يُعدّ لها 1). يقبل txt و gz و zip (يُكتشف من محتوى الملف).
القواعد: إسقاط الهمزة من أول الكلمة (أحمد←احمد)، ة←ه بآخر الكلمة، ى←ي بآخر الكلمة، ؤ←و، ئ←ي.
الأمان: لا يُخرج الخطأ إذا كان كلمة شائعة بنفسه (عدّه > ratio × عدّ الصواب)، أو موجودًا بـ ar_fix.txt اليدوي
أو بقاموس ar_core/ar_extra، أو ملتبسًا بين كلمتين متقاربتي التردّد.
الملف الناتج يُعاد توليده بالكامل كل مرة؛ التصحيحات اليدوية تبقى في ar_fix.txt وتتغلّب عليه عند التعارض.
"""
import argparse, collections, gzip, io, os, re, sys, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
DICT = os.path.join(HERE, '..', 'app', 'src', 'main', 'assets', 'dict')
AR = re.compile(r'^[\u0621-\u064A]+$')   # حروف عربية فقط (بدون تشكيل أو أرقام)


def open_text(path):
    with open(path, 'rb') as f:
        magic = f.read(4)
    if magic[:2] == b'\x1f\x8b':
        return io.TextIOWrapper(gzip.open(path, 'rb'), encoding='utf-8', errors='replace')
    if magic[:2] == b'PK':
        z = zipfile.ZipFile(path)
        names = [n for n in z.namelist() if not n.endswith('/')]
        return io.TextIOWrapper(z.open(names[0]), encoding='utf-8', errors='replace')
    return open(path, encoding='utf-8', errors='replace')


def load_freq(paths, floor):
    freq = collections.Counter()
    for p in paths:
        with open_text(p) as f:
            for line in f:
                parts = line.strip().lstrip('\ufeff').split()
                if not parts or not AR.match(parts[0]):
                    continue
                try:
                    c = int(parts[1]) if len(parts) > 1 else 1
                except ValueError:
                    c = 1
                if c >= floor:
                    freq[parts[0]] += c
    return freq


def load_set(name):
    p = os.path.join(DICT, name)
    if not os.path.exists(p):
        return set()
    with open(p, encoding='utf-8') as f:
        return {l.split('\t')[0].strip() for l in f if l.strip() and not l.startswith('#')}


def variants(w):
    out = set()
    if w[0] in 'أإآ':
        out.add('ا' + w[1:])
    if w.endswith('ة'):
        out.add(w[:-1] + 'ه')
    if w.endswith('ى'):
        out.add(w[:-1] + 'ي')
    if 'ؤ' in w:
        out.add(w.replace('ؤ', 'و'))
    if 'ئ' in w:
        out.add(w.replace('ئ', 'ي'))
    out.discard(w)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--freq', action='append', required=True)
    ap.add_argument('--out', default='-')
    ap.add_argument('--min-count', type=int, default=200)
    ap.add_argument('--ratio', type=float, default=0.05)
    ap.add_argument('--min-len', type=int, default=4)
    ap.add_argument('--max-pairs', type=int, default=6000)
    ap.add_argument('--source', default='')
    a = ap.parse_args()

    # نحمّل حتى الكلمات النادرة نسبيًا: نحتاج عدّ الصيغة الخاطئة لنقارنه بعدّ الصحيحة
    floor = max(1, int(a.min_count * a.ratio))
    freq = load_freq(a.freq, floor)
    valid = load_set('ar_core.txt') | load_set('ar_extra.txt')
    have = load_set('ar_fix.txt')

    cand = collections.defaultdict(list)          # خطأ ← [(صواب، عدّ)]
    for w, c in freq.items():
        if c < a.min_count or len(w) < a.min_len:
            continue
        for v in variants(w):
            if v in have or v in valid:
                continue
            if freq.get(v, 0) > c * a.ratio:      # الصيغة الخاطئة شائعة فعلًا: قد تكون كلمة صحيحة أو اسمًا
                continue
            cand[v].append((w, c))

    rows = []
    for v, lst in cand.items():
        lst.sort(key=lambda t: -t[1])
        if len(lst) > 1 and lst[1][1] * 10 > lst[0][1]:
            continue                               # التباس بين كلمتين متقاربتين
        rows.append((v, lst[0][0], lst[0][1]))
    rows.sort(key=lambda r: (-r[2], r[0]))
    rows = rows[:a.max_pairs]

    out = sys.stdout if a.out == '-' else open(a.out, 'w', encoding='utf-8', newline='\n')
    out.write('# generated by tools/build_ar_fix.py - do not edit by hand (manual fixes go in ar_fix.txt)\n')
    if a.source:
        out.write(f'# source: {a.source} (word frequencies from OpenSubtitles via FrequencyWords, CC BY-SA 4.0)\n')
    for v, w, _ in rows:
        out.write(f'{v}\t{w}\n')
    if out is not sys.stdout:
        out.close()
    print(f'{len(rows)} pairs written from {len(freq)} words', file=sys.stderr)


if __name__ == '__main__':
    main()
